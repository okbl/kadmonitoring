import test from 'node:test';
import assert from 'node:assert/strict';
import { R } from './load.mjs';

const kind = (title, content, instance) => R.classify({ title, content: content || '', extra: [], instance: instance || '' });

test('процессуальное определение не принимается за итог спора', () => {
  // Содержание почти каждого определения называет предмет заявления —
  // «о признании сделки недействительной». Итог — только по словам итога.
  const cases = [
    ['Определение', 'О принятии заявления о признании сделки недействительной к производству', 'accepted', 'accepted'],
    ['Определение', 'О принятии к производству заявления о признании сделки недействительной', 'accepted', 'accepted'],
    ['Определение', 'Об отложении рассмотрения заявления о признании сделки недействительной', 'postponed', 'pending'],
    ['Определение', 'Об оставлении заявления о признании сделки недействительной без движения', 'noMovement', 'noMovement'],
    ['Определение', 'О продлении срока оставления заявления без движения', 'noMovement', 'noMovement'],
    ['Определение', 'Об истребовании доказательств', 'evidence', 'pending'],
    ['Определение', 'О приостановлении производства по заявлению о признании сделки недействительной', 'suspended', 'suspended'],
    ['Определение', 'О возвращении заявления о признании сделки недействительной', 'returned', 'returned'],
    ['Определение', 'Об отказе в принятии заявления', 'refusedAccept', 'refused'],
    ['Определение', 'О принятии отказа от заявления и прекращении производства', 'terminated', 'terminated'],
    ['Определение', 'Об отказе в удовлетворении ходатайства о фальсификации', 'motionDenied', null],
    ['Определение', 'Об удовлетворении заявления о признании сделки недействительной', 'granted', 'granted'],
    ['Определение', 'О признании сделки недействительной и применении последствий ее недействительности', 'granted', 'granted'],
    ['Определение', 'Об удовлетворении заявления частично', 'partly', 'partly'],
    ['Определение', 'Об отказе в удовлетворении заявления о признании сделки недействительной', 'denied', 'denied']
  ];
  for (const [t, c, k, st] of cases) {
    const r = kind(t, c);
    assert.equal(r.kind, k, `${c} → ${r.kind}`);
    assert.equal(r.stage, st, `${c}: стадия`);
  }
});

test('документы сторон: начало спора отличается от документов по ходу спора', () => {
  assert.equal(kind('Заявление', 'О признании сделки недействительной').kind, 'application');
  assert.equal(kind('Заявление', 'Об уточнении требований о признании сделки недействительной').kind, 'amend');
  assert.equal(kind('Заявление', 'Об отказе от заявления о признании сделки недействительной').kind, 'withdraw');
  assert.equal(kind('Дополнительные документы', 'Во исполнение определения об оставлении без движения').kind, 'fixDefects');
  assert.equal(kind('Отзыв', 'На заявление о признании сделки недействительной').kind, 'response');
  assert.equal(kind('Заявление', 'О включении в реестр требований кредиторов').stage, null, 'чужое заявление спор не начинает');
});

test('определения апелляции двигают жалобу, а не спор', () => {
  const r = kind('Определение', 'О принятии апелляционной жалобы к производству');
  assert.equal(r.kind, 'appealProc');
  assert.equal(r.stage, 'appeal');
  assert.equal(kind('Определение', 'Об отложении судебного разбирательства', 'Апелляция').stage, 'appeal');
  assert.equal(kind('Постановление апелляционной инстанции', '').stage, 'appealDone');
});

test('название «Определение» без содержания уточняется по резолютивной части', () => {
  const r = R.classify({ title: 'Определение', content: '', extra: [] }, 'Оставить заявление без движения.');
  assert.equal(r.kind, 'noMovement');
});

test('разбор текста определения: резолютивная часть, сроки, заседание, адресаты', () => {
  const text = `АРБИТРАЖНЫЙ СУД ГОРОДА МОСКВЫ
О П Р Е Д Е Л Е Н И Е
Определением от 01.06.2026 суд определил: истребовать документы в срок до 10.06.2026.
Руководствуясь статьями 184, 185 АПК РФ, суд
О П Р Е Д Е Л И Л:
Принять заявление ПАО Сбербанк о признании сделки недействительной к производству.
Назначить судебное заседание на 12 августа 2026 года на 10 час. 30 мин.
Финансовому управляющему представить отзыв на заявление в срок до
05.08.2026.
Лицам, участвующим в деле, представить письменные позиции в течение пяти дней.
Заявителю направить копии заявления лицам, участвующим в деле.`;
  const r = R.parseRuling(text);
  assert.equal(r.hasResolution, true);
  assert.equal(r.kindHint, 'accepted');
  assert.deepEqual([r.hearing.date, r.hearing.time], ['2026-08-12', '10:30']);
  assert.equal(r.deadlines[0].date, '2026-08-05', 'срок из описательной части (10.06.2026) не берётся');
  const fm = r.demands.find((d) => d.toFinancialManager);
  assert.match(fm.text, /до 05\.08\.2026/, 'строка, перенесённая по ширине страницы, склеена');
  assert.equal(fm.date, '2026-08-05');
  const all = r.demands.find((d) => d.toAll && !d.toApplicant);
  assert.equal(all.days, 5);
});

test('срок обжалования — из текста определения; заседание — только из резолютивной части', () => {
  const text = `Определением от 29.06.2026 рассмотрение заявления назначено на 21 июля 2026 года.
Руководствуясь статьями 61.8, 184 АПК РФ, арбитражный суд
О П Р Е Д Е Л И Л:
1. Заявление публичного акционерного общества «Сбербанк России» удовлетворить.
2. Признать недействительным договор купли-продажи автомобиля от 22.01.2024.
5. Определение может быть обжаловано в порядке апелляционного производства в Семнадцатый арбитражный
апелляционный суд в течение месяца со дня его принятия.`;
  const r = R.parseRuling(text);
  assert.equal(r.kindHint, 'granted');
  assert.deepEqual([r.appeal.months, r.appeal.days], [1, 0]);
  assert.equal(r.hearing, null, 'прошедшее заседание из описательной части не берётся');
});
